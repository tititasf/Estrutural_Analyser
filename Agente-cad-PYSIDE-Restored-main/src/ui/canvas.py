        if key == Qt.Key_F8:
            self.toggle_ortho(); return

        # Atalhos de EdiÃ§Ã£o (Somente se nÃ£o estiver em picking)
        if not self.picking_mode:
            if key == Qt.Key_L: self.set_edit_mode('line'); return
