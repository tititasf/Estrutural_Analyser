    def _apply_ortho(self, start, current):
        """Aplica restriÃ§Ã£o ortogonal se ativa"""
        if not self.ortho_mode: return current
        dx = abs(current.x() - start.x())
        dy = abs(current.y() - start.y())
        if dx > dy: return QPointF(current.x(), start.y())
        else: return QPointF(start.x(), current.y())

    def _dist_point_to_segment(self, p, a, b):
        """Calcula a distÃ¢ncia perpendicular de um ponto P a um segmento AB."""
        px, py = p.x(), p.y()
        ax, ay = a.x(), a.y()
        bx, by = b.x(), b.y()
        
        l2 = (ax - bx)**2 + (ay - by)**2
        if l2 == 0: return math.hypot(px - ax, py - ay)
        
        t = ((px - ax) * (bx - ax) + (py - ay) * (by - ay)) / l2
        t = max(0, min(1, t))
        
        projections_x = ax + t * (bx - ax)
        projections_y = ay + t * (by - ay)
        return math.hypot(px - projections_x, py - projections_y)

    def _get_closest_item(self, scene_pos, items):
        """Retorna o item visual mais prÃ³ximo do ponto especificado."""
        if not items: return None
        best_item = None
        min_dist = 9999.0
        
        for item in items:
            dist = 999.0
            if isinstance(item, QGraphicsLineItem):
                dist = self._dist_point_to_segment(scene_pos, item.line().p1(), item.line().p2())
            elif isinstance(item, (PillarGraphicsItem, SlabGraphicsItem, BeamGraphicsItem)):
                # DistÃ¢ncia ao centro do bounding box (padrÃ£o para objetos complexos)
                center = item.mapToScene(item.boundingRect().center())
                dist = math.hypot(scene_pos.x() - center.x(), scene_pos.y() - center.y())
            elif isinstance(item, QGraphicsPathItem):
                # [PRECISION FIX] Se o ponto estÃ¡ CONTIDO no path ou muito perto da borda.
                # Como jÃ¡ filtramos por um rect de 1px, se ele estÃ¡ aqui, ele Ã© um candidato vÃ¡lido.
                # Priorizamos a distÃ¢ncia Ã  borda para caminhos (polilinhas/hachuras)
                dist = 0.5 # Valor baixo para priorizar caminhos sobre bounding boxes genÃ©ricos
                # Tentar encontrar a menor distÃ¢ncia real aos segmentos do path seria ideal, 
                # mas como o rect jÃ¡ Ã© de 1px, qualquer item aqui estÃ¡ a < 1px.
                # O problema era usar o centro do bounding box que jogava a distÃ¢ncia para o infinito.
            elif isinstance(item, QGraphicsSimpleTextItem):
                center = item.mapToScene(item.boundingRect().center())
                dist = math.hypot(scene_pos.x() - center.x(), scene_pos.y() - center.y())
            
            if dist < min_dist:
                min_dist = dist
                best_item = item
        return best_item

