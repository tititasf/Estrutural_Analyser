                if self.compute_snaps:
                    p_last = points[-1]
                    p_first = points[0]
                    self.snap_segments.append((p_last, p_first))
                    calc_lines.append({'start': p_last, 'end': p_first})
                    mid = ((p_last[0]+p_first[0])/2, (p_last[1]+p_first[1])/2)
