import logging
import re
from typing import List, Dict, Tuple
from shapely.geometry import Point, LineString, Polygon
from .spatial_index import SpatialIndex

class BeamTracer:
    """
    Motor especializado em identificar vigas baseadas em nomes (V1, V2...)
    e traçar seu caminho geométrico entre apoios.
    """
    def __init__(self, spatial_index: SpatialIndex, learning_params_bottom: dict = None):
        self.spatial_index = spatial_index
        # [BOTTOM]
        self.learning_params_bottom = learning_params_bottom or {}
    def detect_beams(self, texts: List[Dict], all_lines: List[Dict]) -> List[Dict]:
        """
        Identifica vigas a partir de textos que seguem o padrão V + Número.
        Diferencia sufixos:
        - V1a (minúsculo): Segmento de viga.
        - V1A (maiúsculo): Outra viga.
        Se múltiplos itens tiverem o mesmo nome (ex: V1), gera sufixos automáticos (V1a, V1b...).
        """
        raw_beams = []
        for txt in texts:
            content = txt['text'].strip()
            # Padrão: V1, V2, V10A, V1a, CONT. V1 etc. (Case Sensitive agora)
            if (content.startswith('V') or content.startswith('v') or content.upper().startswith('CONT')) and any(c.isdigit() for c in content):
                pos = txt['pos']
                geometry = self._find_beam_geometry(pos, all_lines)
                if geometry:
                    raw_beams.append({
                        'name': content,
                        'type': 'Viga',
                        'pos': pos,
                        'geometry': geometry,
                        'neighbors': []
                    })
        
        # Pós-processamento para combinar vigas com o mesmo base name e deduplicar geometrias
        import re
        final_beams = []
        grouped_by_base = {}
        
        for b in raw_beams:
            raw_name = b['name'].upper()
            clean_name = raw_name.replace('CONT.', '').replace('CONT', '').strip()
            # Extrair V301, VF203 ignorando pontuações e sufixos finais
            m = re.match(r'^(V|VF)\s*(\d+)', clean_name)
            if m:
                base_name = f"{m.group(1)}{m.group(2)}"
            else:
                base_name = clean_name
                
            if base_name not in grouped_by_base:
                grouped_by_base[base_name] = []
            grouped_by_base[base_name].append(b)
            
        for base_name, beam_list in grouped_by_base.items():
            if len(beam_list) == 1:
                b = beam_list[0]
                b['name'] = base_name
                b['parent_name'] = base_name
                final_beams.append(b)
                continue
                
            # Combinar múltiplas vigas
            master_beam = {
                'name': base_name,
                'parent_name': base_name,
                'type': 'Viga',
                'pos': beam_list[0]['pos'], 
                'geometry': {
                    'lines': [],
                    'texts': [],
                    'dimension_texts': [],
                    'classified': {'seg_side_a': [], 'seg_side_b': [], 'seg_bottom': [], 'merged_bottom_lengths': []}
                },
                'neighbors': []
            }
            
            seen_centers = set()
            seg_longitudinais = []
            
            for b in beam_list:
                geo = b['geometry']
                master_beam['geometry']['lines'].extend(geo.get('lines', []))
                master_beam['geometry']['texts'].extend(geo.get('texts', []))
                master_beam['geometry']['dimension_texts'].extend(geo.get('dimension_texts', []))
                
                classi = geo.get('classified', {})
                master_beam['geometry']['classified']['seg_side_a'].extend(classi.get('seg_side_a', []))
                master_beam['geometry']['classified']['seg_side_b'].extend(classi.get('seg_side_b', []))
                
                for seg in classi.get('seg_bottom', []):
                    cx = round(sum(p[0] for p in seg) / len(seg), 1)
                    cy = round(sum(p[1] for p in seg) / len(seg), 1)
                    if (cx, cy) not in seen_centers:
                        seen_centers.add((cx, cy))
                        master_beam['geometry']['classified']['seg_bottom'].append(seg)
                        seg_longitudinais.append({
                            'line': seg,
                            'dx': max(p[0] for p in seg) - min(p[0] for p in seg),
                            'dy': max(p[1] for p in seg) - min(p[1] for p in seg)
                        })
            
            # Recalcular merged_bottom_lengths e agrupar as polilinhas reais do CAD (em vez de caixas genéricas)
            medidas_tracer = []
            merged_groups = []
            if seg_longitudinais:
                largest_seg = max(seg_longitudinais, key=lambda x: max(x['dx'], x['dy']))
                is_horizontal = largest_seg['dx'] > largest_seg['dy']
                
                # Coleta limites globais da viga para fechar o retângulo perfeito
                pts_a = [p for seg in master_beam['geometry']['classified'].get('seg_side_a', []) for p in seg]
                pts_b = [p for seg in master_beam['geometry']['classified'].get('seg_side_b', []) for p in seg]
                all_beam_pts = pts_a + pts_b
                if not all_beam_pts:
                    for seg in master_beam['geometry']['classified'].get('seg_bottom', []):
                        all_beam_pts.extend(seg)
                
                min_y = min((p[1] for p in all_beam_pts), default=0)
                max_y = max((p[1] for p in all_beam_pts), default=20)
                min_x = min((p[0] for p in all_beam_pts), default=0)
                max_x = max((p[0] for p in all_beam_pts), default=20)
                
                # Trava de segurança para larguras irreais geradas por ruído no CAD
                if max_y - min_y > 80 and is_horizontal:
                    mid_y = (max_y + min_y) / 2
                    min_y, max_y = mid_y - 15, mid_y + 15
                if max_x - min_x > 80 and not is_horizontal:
                    mid_x = (max_x + min_x) / 2
                    min_x, max_x = mid_x - 15, mid_x + 15
                
                if is_horizontal:
                    seg_longitudinais.sort(key=lambda x: min(p[0] for p in x['line']))
                    current_min = min(p[0] for p in seg_longitudinais[0]['line'])
                    current_max = max(p[0] for p in seg_longitudinais[0]['line'])
                    
                    for i in range(1, len(seg_longitudinais)):
                        pts = seg_longitudinais[i]['line']
                        item_min = min(p[0] for p in pts)
                        item_max = max(p[0] for p in pts)
                        
                        if item_min - current_max <= 2.0:
                            current_max = max(current_max, item_max)
                        else:
                            if current_max - current_min > 10.0:
                                medidas_tracer.append(current_max - current_min)
                                rect = [[current_min, min_y], [current_max, min_y], [current_max, max_y], [current_min, max_y], [current_min, min_y]]
                                merged_groups.append([rect])
                            current_min = item_min
                            current_max = item_max
                            
                    if current_max - current_min > 10.0:
                        medidas_tracer.append(current_max - current_min)
                        rect = [[current_min, min_y], [current_max, min_y], [current_max, max_y], [current_min, max_y], [current_min, min_y]]
                        merged_groups.append([rect])
                else:
                    seg_longitudinais.sort(key=lambda x: min(p[1] for p in x['line']))
                    current_min = min(p[1] for p in seg_longitudinais[0]['line'])
                    current_max = max(p[1] for p in seg_longitudinais[0]['line'])
                    
                    for i in range(1, len(seg_longitudinais)):
                        pts = seg_longitudinais[i]['line']
                        item_min = min(p[1] for p in pts)
                        item_max = max(p[1] for p in pts)
                        
                        if item_min - current_max <= 2.0:
                            current_max = max(current_max, item_max)
                        else:
                            if current_max - current_min > 10.0:
                                medidas_tracer.append(current_max - current_min)
                                rect = [[min_x, current_min], [max_x, current_min], [max_x, current_max], [min_x, current_max], [min_x, current_min]]
                                merged_groups.append([rect])
                            current_min = item_min
                            current_max = item_max
                            
                    if current_max - current_min > 10.0:
                        medidas_tracer.append(current_max - current_min)
                        rect = [[min_x, current_min], [max_x, current_min], [max_x, current_max], [min_x, current_max], [min_x, current_min]]
                        merged_groups.append([rect])
            else:
                # Fallback: a viga inteira é 1 único segmento de fundo (não há tracinhos divisores)
                pts_a = [p for seg in master_beam['geometry']['classified'].get('seg_side_a', []) for p in seg]
                pts_b = [p for seg in master_beam['geometry']['classified'].get('seg_side_b', []) for p in seg]
                all_beam_pts = pts_a + pts_b
                if all_beam_pts:
                    min_y = min((p[1] for p in all_beam_pts), default=0)
                    max_y = max((p[1] for p in all_beam_pts), default=20)
                    min_x = min((p[0] for p in all_beam_pts), default=0)
                    max_x = max((p[0] for p in all_beam_pts), default=20)
                    
                    dx = max_x - min_x
                    dy = max_y - min_y
                    
                    if dx > dy:
                        if max_y - min_y > 80:
                            mid_y = (max_y + min_y) / 2
                            min_y, max_y = mid_y - 15, mid_y + 15
                    else:
                        if max_x - min_x > 80:
                            mid_x = (max_x + min_x) / 2
                            min_x, max_x = mid_x - 15, mid_x + 15
                            
                    medidas_tracer = [max(dx, dy)]
                    rect = [[min_x, min_y], [max_x, min_y], [max_x, max_y], [min_x, max_y], [min_x, min_y]]
                    merged_groups = [[rect]]
            
            master_beam['geometry']['classified']['merged_bottom_lengths'] = medidas_tracer
            master_beam['geometry']['classified']['merged_bottom_groups'] = merged_groups
            final_beams.append(master_beam)
            
        # Atribuir IDs finais
        for i, b in enumerate(final_beams):
            b['id'] = f"beam_{b['name']}_{i}"
            
        return final_beams

    def _find_beam_geometry(self, pos: Tuple[float, float], all_lines: List[Dict]) -> Dict:
        """
        Encontra e CLASSIFICA geometrias (linhas e textos) vinculados a uma viga.
        Agora busca também dimensões, candidatos a lajes e apoios.
        """
        # [LEARNING] Raio de Busca Dinamico
        sensibilidade = 1.0
        if hasattr(self, 'learning_params_bottom') and self.learning_params_bottom:
            sensibilidade = self.learning_params_bottom.get('segmentation_sensitivity', 1.0)
            
        raio_busca = 800 * sensibilidade
        raio_geometria = 500 * sensibilidade

        # Area de busca ampliada dinamicamente para capturar textos de dimensao e apoios proximos
        search_area = (pos[0]-raio_busca, pos[1]-raio_busca, pos[0]+raio_busca, pos[1]+raio_busca)
        candidates = self.spatial_index.query_bbox(search_area)
        
        beam_geometry = {
            'lines': [],
            'texts': [],
            'dimension_texts': [],
            'support_candidates': [],
            'slab_candidates': [],
            'classified': {'seg_side_a': [], 'seg_side_b': [], 'seg_bottom': []}
        }
        
        # [ALGORITMO ULTRAINTELIGENTE] - Region Growing
        # 1. Acha as "sementes" (linhas que estao proximas do texto inicial)
        sementes = []
        # Usa um raio restrito para pegar linhas de chamada (leader lines) e crescer a partir delas, sem poluir o centro geométrico
        seed_radius = max(150, int(raio_busca * 0.3))
        seed_area = (pos[0]-seed_radius, pos[1]-seed_radius, pos[0]+seed_radius, pos[1]+seed_radius)
        seed_cands = self.spatial_index.query_bbox(seed_area)
        
        for cand in seed_cands:
            if isinstance(cand, dict) and 'points' in cand:
                sementes.append(cand)
                
        # 2. Caminha pelas conexoes (Tolerancia dinamica ampliada)
        conn_tol = 30 * sensibilidade
        visited_ids = set()
        queue = []
        
        for s in sementes:
            if id(s) not in visited_ids:
                visited_ids.add(id(s))
                queue.append(s)
                beam_geometry['lines'].append(s['points'])
                
        while queue:
            curr = queue.pop(0)
            for pt in curr['points']:
                bbox = (pt[0]-conn_tol, pt[1]-conn_tol, pt[0]+conn_tol, pt[1]+conn_tol)
                vizinhos = self.spatial_index.query_bbox(bbox)
                for cand in vizinhos:
                    if isinstance(cand, dict) and 'points' in cand:
                        if id(cand) not in visited_ids:
                            visited_ids.add(id(cand))
                            queue.append(cand)
                            beam_geometry['lines'].append(cand['points'])
                        
        raw_lines = beam_geometry['lines']

        # Coleta textos e apoios usando a Bounding Box TOTAL da viga mapeada
        if raw_lines:
            all_x = [p[0] for l in raw_lines for p in l]
            all_y = [p[1] for l in raw_lines for p in l]
            min_x, max_x = min(all_x), max(all_x)
            min_y, max_y = min(all_y), max(all_y)
            
            # Expande um pouco para capturar textos laterais
            total_bbox = (min_x-100, min_y-100, max_x+100, max_y+100)
            full_cands = self.spatial_index.query_bbox(total_bbox)
            
            for cand in full_cands:
                if isinstance(cand, dict):
                    if 'layer' in cand and ('PILAR' in cand['layer'].upper() or 'COL' in cand['layer'].upper()):
                         beam_geometry['support_candidates'].append(cand)
                    elif 'text' in cand:
                        content = cand['text'].strip()
                        if re.search(r'\d+[x\/\*]\d+', content):
                            beam_geometry['dimension_texts'].append(cand)
                        elif re.match(r'^[L|l]\d+', content):
                            beam_geometry['slab_candidates'].append(cand)
                        else:
                            beam_geometry['texts'].append(cand)
                            
        # 2. Classificacao Geometrica dos Segmentos
        if len(raw_lines) >= 2:
             classification = self._classify_lines(pos, raw_lines)
             beam_geometry['classified'] = classification

        return beam_geometry

    def _point_dist(self, p1, p2):
        return ((p1[0]-p2[0])**2 + (p1[1]-p2[1])**2)**0.5

    def _classify_lines(self, center: Tuple[float, float], lines: List[List[Tuple[float, float]]]) -> Dict:
        """
        Classifica linhas em Lado A, Lado B e Fundo baseado na posicao relativa ao centro.
        Assumes horizontal or vertical beams mostly.
        """
        classified = {'seg_side_a': [], 'seg_side_b': [], 'seg_bottom': []}
        valid_lines = []
        horizontal_weight = 0
        vertical_weight = 0
        sum_hx, sum_hlen = 0.0, 0.0
        sum_vy, sum_vlen = 0.0, 0.0
        
        for line in lines:
            if len(line) < 2: continue
            
            xs = [p[0] for p in line]
            ys = [p[1] for p in line]
            min_x, max_x = min(xs), max(xs)
            min_y, max_y = min(ys), max(ys)
            
            dx = max_x - min_x
            dy = max_y - min_y
            length = max(dx, dy)
            
            if length < 10: continue # Ignora linhas muito curtas (ruido)
            
            cx, cy = (min_x+max_x)/2.0, (min_y+max_y)/2.0
            if dx > dy: 
                horizontal_weight += length
                sum_vy += cy * length
                sum_vlen += length
            else: 
                vertical_weight += length
                sum_hx += cx * length
                sum_hlen += length
                
            valid_lines.append({'line': line, 'dx': dx, 'dy': dy, 'len': length, 'center': (cx, cy)})

        # Define a orientação primária e o centro geométrico com base nos polígonos fechados primeiro
        bottom_cands = [item for item in valid_lines if len(item['line']) >= 4 and abs(item['line'][0][0] - item['line'][-1][0]) < 1.0 and abs(item['line'][0][1] - item['line'][-1][1]) < 1.0]
        if bottom_cands:
            largest_bottom = max(bottom_cands, key=lambda x: x['len'])
            is_horizontal = largest_bottom['dx'] > largest_bottom['dy']
            
            geo_center_x = sum(c['center'][0] * c['len'] for c in bottom_cands) / sum(c['len'] for c in bottom_cands)
            geo_center_y = sum(c['center'][1] * c['len'] for c in bottom_cands) / sum(c['len'] for c in bottom_cands)
            geo_center = (geo_center_x, geo_center_y)
        else:
            is_horizontal = horizontal_weight > vertical_weight
            geo_center_x = sum_hx / sum_hlen if sum_hlen > 0 else 0
            geo_center_y = sum_vy / sum_vlen if sum_vlen > 0 else 0
            geo_center = (geo_center_x, geo_center_y)
        
        bottom_candidates = []
        for item in valid_lines:
            line = item['line']
            lc = item['center']
            dx, dy = item['dx'], item['dy']
            length = item['len']
            
            is_perpendicular = (is_horizontal and dy > dx) or \
                               (not is_horizontal and dx > dy)
                               
            is_closed = len(line) >= 4 and self._point_dist(line[0], line[-1]) < 5.0
            
            # Se for polígono fechado, o eixo menor deve ser a largura da viga (ex: 10 a 60cm).
            # Se for muito largo, não é um fundo de viga individual.
            if is_closed:
                width = min(dx, dy)
                if width > 80:
                    is_closed = False # Falso positivo, pode ser uma laje
            
            # Condições para ser fundo:
            # 1. É uma linha solta perpendicular (divisória) de tamanho razoável
            # 2. É um polígono fechado PARALELO à viga, E está próximo ao CENTRO GEOMÉTRICO do desenho
            is_valid_bottom = False
            
            if not is_closed and is_perpendicular and length <= 80:
                is_valid_bottom = True
            elif is_closed and not is_perpendicular:
                # Checagem de distância ao centro geométrico do bloco para achar a chapa do meio (Fundo)
                if is_horizontal:
                    dist_to_center = abs(lc[1] - geo_center[1])
                    if dist_to_center < 30.0: # Fundo fica no meio, laterais ficam afastadas
                        is_valid_bottom = True
                else:
                    dist_to_center = abs(lc[0] - geo_center[0])
                    if dist_to_center < 30.0:
                        is_valid_bottom = True
            
            if is_valid_bottom:
                bottom_candidates.append(item)
                continue
                
            if is_horizontal:
                if lc[1] > center[1]: # Acima
                    classified['seg_side_a'].append(line)
                else: # Abaixo
                    classified['seg_side_b'].append(line)
            else:
                if lc[0] < center[0]: # Esquerda
                    classified['seg_side_a'].append(line)
                else: # Direita
                    classified['seg_side_b'].append(line)
                    
        # Filtro de desduplicação e prioridade para polígonos sobre linhas soltas
        # Pega apenas os items que realmente formam o fundo
        raw_bottoms = []
        for cand in bottom_candidates:
            raw_bottoms.append(cand)
            classified['seg_bottom'].append(cand['line'])
            
        # Agrupar chapas (Merge Logic igual ao N2): Se a distancia X entre as chapas for pequena (< 15cm), é a mesma chapa!
        if is_horizontal and raw_bottoms:
            # Ordena da esquerda pra direita
            raw_bottoms.sort(key=lambda item: min(p[0] for p in item['line']))
            merged_segments = []
            current_min = min(p[0] for p in raw_bottoms[0]['line'])
            current_max = max(p[0] for p in raw_bottoms[0]['line'])
            
            for i in range(1, len(raw_bottoms)):
                item_min = min(p[0] for p in raw_bottoms[i]['line'])
                item_max = max(p[0] for p in raw_bottoms[i]['line'])
                gap = item_min - current_max
                if gap <= 2.0: # Apenas une se forem falhas minúsculas no CAD. Pilares (>=14cm) vão quebrar o segmento.
                    current_max = max(current_max, item_max)
                else:
                    if current_max - current_min > 10.0:
                        merged_segments.append(current_max - current_min)
                    current_min = item_min
                    current_max = item_max
            if current_max - current_min > 10.0:
                merged_segments.append(current_max - current_min)
            classified['merged_bottom_lengths'] = merged_segments
        elif not is_horizontal and raw_bottoms:
            # Ordena de baixo pra cima
            raw_bottoms.sort(key=lambda item: min(p[1] for p in item['line']))
            merged_segments = []
            current_min = min(p[1] for p in raw_bottoms[0]['line'])
            current_max = max(p[1] for p in raw_bottoms[0]['line'])
            
            for i in range(1, len(raw_bottoms)):
                item_min = min(p[1] for p in raw_bottoms[i]['line'])
                item_max = max(p[1] for p in raw_bottoms[i]['line'])
                gap = item_min - current_max
                if gap <= 2.0:
                    current_max = max(current_max, item_max)
                else:
                    if current_max - current_min > 10.0:
                        merged_segments.append(current_max - current_min)
                    current_min = item_min
                    current_max = item_max
            if current_max - current_min > 10.0:
                merged_segments.append(current_max - current_min)
            classified['merged_bottom_lengths'] = merged_segments
        else:
            classified['merged_bottom_lengths'] = []
            
        return classified
